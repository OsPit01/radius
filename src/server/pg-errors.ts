// РАСПОЗНАВАНИЕ ОШИБОК PostgreSQL ПО КОДУ.
//
// Зачем: unique-индексы в БД (например, partial-индекс «нет двух
// активных заявок на те же даты») гасят гонки, но при конфликте
// выбрасывают ошибку с кодом SQLSTATE '23505'. Чтобы отдать клиенту
// понятный ответ вместо 500, ошибку нужно опознать.
// ============================================================

/** Код SQLSTATE «нарушение уникальности» (unique_violation). */
const UNIQUE_VIOLATION = '23505';

/**
 * true, если ошибка — это «такая строка уже существует» от PostgreSQL.
 * Проверка безопасная: любой не-Error просто не подходит под условие.
 */
export function isUniqueViolation(error: unknown): boolean {
    if (!(error instanceof Error) || !('code' in error)) {
        return false;
    }
    return error.code === UNIQUE_VIOLATION;
}
