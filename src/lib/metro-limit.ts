/**
 * Метро показываем (в форме, на карточке, на странице объекта) и подставляем, только если до него МЕНЬШЕ стольких минут
 * пешком: дальше это уже не «рядом с метро». Фильтр «до N минут пешком» (FilterPanel) идёт до 30 — внутри этого порога.
 *
 * Отдельный файл без справочника станций: карточка объекта на главной тянет только эту проверку, а не 11 КБ станций.
 */
export const METRO_WALK_LIMIT_MINUTES = 40;

/**
 * Можно ли показывать метро с таким временем. В базе минуты хранятся строкой («25»), в форме — числом;
 * пусто, 0 и всё, что не число, — «неизвестно».
 */
export function isMetroWalkable(minutes: number | string | null | undefined): boolean {
    const value = Number(minutes);
    return Number.isFinite(value) && value > 0 && value < METRO_WALK_LIMIT_MINUTES;
}
