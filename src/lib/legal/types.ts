// ============================================================
// src/lib/legal/types.ts — ТИПЫ ЮРИДИЧЕСКИХ ДОКУМЕНТОВ
// ============================================================
//
// Каждый юридический документ (Политика, Соглашение, Cookie-политика,
// Согласие) описывается ДАННЫМИ, а не вёрсткой: массив разделов,
// внутри — блоки (абзац / список / таблица / заметка).
//
// Зачем так:
// 1. Оглавление страницы строится автоматически из тех же данных,
//    что и текст, — ссылка не может «разъехаться» с заголовком.
// 2. Текст живёт в src/lib/legal/, а вёрстка — один раз в
//    src/components/legal/LegalDocument.tsx. Меняем текст — не трогаем разметку.
// 3. У документа есть версия и дата — это нужно, чтобы фиксировать,
//    какую редакцию пользователь принял (требование доказуемости согласия).
// ============================================================

import type { ReactNode } from 'react';

/** Один блок внутри раздела документа. */
export type LegalBlock =
    /** Обычный абзац. */
    | { kind: 'p'; children: ReactNode }
    /** Список: маркированный (по умолчанию) или нумерованный. */
    | { kind: 'list'; items: ReactNode[]; ordered?: boolean }
    /**
     * Таблица. На телефоне рисуется карточками (строка → карточка),
     * на планшете/десктопе — обычной таблицей. Так страница никогда
     * не получает горизонтальный скролл на 360px.
     */
    | { kind: 'table'; head: string[]; rows: ReactNode[][] }
    /** Выделенная заметка («важно»). */
    | { kind: 'notice'; children: ReactNode };

/** Раздел документа. `id` — якорь для ссылок вида /terms#landlord. */
export type LegalSection = {
    id: string;
    title: string;
    blocks: LegalBlock[];
};

/** Полный документ: метаданные + разделы. */
export type LegalDocumentData = {
    /** Путь страницы: '/privacy'. */
    slug: string;
    /** Заголовок H1 на странице. */
    title: string;
    /** Как документ называется в футере (короче). */
    navTitle: string;
    /** Заголовок для <title> и og:title (короткий). */
    seoTitle: string;
    /** Meta description. */
    description: string;
    /** Версия редакции — фиксируется при принятии пользователем. */
    version: string;
    /** Дата последнего обновления (человекочитаемая строка). */
    updatedAt: string;
    /** Закрыть страницу от индексации (для служебных документов). */
    noindex?: boolean;
    sections: LegalSection[];
};
