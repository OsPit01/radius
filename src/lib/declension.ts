// Fallback: города нет в словаре → функция вернёт null
//  Минск есть в словаре - значит в Минске
// Москва нет в словаре вернет null, например: Квартиры на сутки в городе Москва
// если не знакомый город подставляем город и будет звучать уже так например в Москва - плохо, в городе Москва - норм:)
export function cityInPrepositional(name: string): string | null {
    return PREPOSITIONAL[name] ?? null;
}

/** Области: «Витебская область» → «Витебской области» (предложный падеж).
 *  Все 6 областей заканчиваются на «…ская область» — одно правило закрывает все.
 *  Незнакомый формат replace оставит как есть (без совпадения строка не меняется). */
export function regionInPrepositional(label: string): string {
    return label.replace(/ская область$/u, 'ской области');
}

// ===== Районы Минска для SEO-заголовков страниц каталога =====
// Заголовок строится как «Квартиры на сутки {значение}» — БЕЗ предлога:
// именно так формулируют поисковый запрос («квартира на сутки маяк минска»),
// название района = бренд, не склоняется и не требует предлога.
// Формы с предлогами («у Маяка», «в Новой Боровой») звучали искусственно
// и порождали двойные «на на» («на сутки на Немиге»).
const DISTRICT_PREPOSITIONAL: Record<string, string> = {
    // ПУСТ намеренно: районы подставляются своим именем как есть (см. ниже).
    // Сюда писать ТОЛЬКО если какому-то району нужна особая форма,
    // которая не строится из имени автоматически.
};

/**
 * Район для заголовка: просто имя, без предлога и склонения.
 * «Маяк Минска» → «Маяк Минска» (как в поисковом запросе).
 * Незнакомый район — тоже просто имя: грамматика не ломается никогда,
 * потому что имя не встраивается в предложение, а стоит рядом.
 */
export function districtInPrepositional(name: string): string {
    return DISTRICT_PREPOSITIONAL[name] ?? name;
}
