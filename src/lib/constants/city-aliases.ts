// Карта «населённый пункт → город каталога»: пригороды и спутники, которые
// для витрины считаются частью ближайшего города. Яндекс отдаёт их как
// отдельные locality («Копище», «Колодищи») — без этой карты в каталоге
// плодились бы города-дубли («Копище» и «Минск» — два города, один рынок).
//
// ЕДИНЫЙ источник: применяется на входе (геокодер/формы) ДО записи в БД.
// Ключи и значения — канонические имена (как в belarus-locations.ts).
// Если пункта в карте нет — город остаётся как есть (Бобруйск остаётся Бобруйском).
export const CITY_ALIASES: Record<string, string> = {
    // Минск: пригороды и коттеджные посёлки, которые ищут как «Минск»
    Копище: 'Минск',
};

/** Канонический город каталога для населённого пункта. Нет в карте — вернём как есть. */
export function getCatalogCity(locality: string): string {
    return CITY_ALIASES[locality] ?? locality;
}
